"""Application constants and default configuration.

This module defines seed categories, default rules, and app-wide
constants.  It has no Kivy or SQLite imports so it can be used
freely by the logic and data layers.

How to add future keywords:
1. Locate the appropriate category section in `DEFAULT_RULES`.
2. Add a 4-tuple: `(pattern, category_name, priority, match_mode)`:
   - `pattern`: Lowercase string (spaces, punctuation, hyphens allowed).
   - `category_name`: Must be one of `DEFAULT_CATEGORIES`.
   - `priority`: Integer (standard baseline is 10; higher priority wins in ties).
   - `match_mode`:
     - `"whole_word"`: Recommended for single words and short phrases so they
       do not trigger on unrelated substrings (e.g. `fare` vs `farewell`,
       `rice` vs `price`).
     - `"substring"`: Recommended for distinctive multiword phrases or unique
       proper nouns/brand names (e.g. `mercury drug`, `water bill`).
3. Ensure the pattern is unique and does not introduce ambiguous conflicts.
4. Run tests (`pytest`) to verify matching behavior.
"""

